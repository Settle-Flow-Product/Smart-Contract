#!/usr/bin/env bash
#
# Shared shell vocabulary for the deployment and demo scripts.
#
# Sourced, never executed. Provides: environment defaults, TTY-aware output helpers, a preflight
# check, and the evidence recorder that writes .deploy/evidence.md as steps complete.
#
# The evidence recorder exists because a transaction hash not captured at the moment it happens is
# a transaction hash gone. See ../../docs/14-evidence.md.

NETWORK="${NETWORK:-testnet}"
case "$NETWORK" in
    testnet) RPC_URL="${RPC_URL:-https://soroban-testnet.stellar.org}"
             HORIZON_URL="${HORIZON_URL:-https://horizon-testnet.stellar.org}"
             PASSPHRASE="${PASSPHRASE:-Test SDF Network ; September 2015}" ;;
    *)       echo "Only testnet is in scope for SOW 1. Mainnet is explicitly out." >&2; exit 1 ;;
esac

# The REPOSITORY ROOT, not this directory. These scripts cd into `smart-contract/`, so a relative
# `.deploy` would land there while `backend/scripts/setup_treasury.sh` writes to the root — one
# deployment split across two directories, and the demo reading only one of them.
DEPLOY_DIR="${DEPLOY_DIR:-../.deploy}"
ENV_FILE="$DEPLOY_DIR/env"
EVIDENCE="$DEPLOY_DIR/evidence.md"

# ---------------------------------------------------------------------------
# Output
# ---------------------------------------------------------------------------

if [ -t 1 ]; then
    C_DIM=$'\033[2m'; C_OK=$'\033[32m'; C_ERR=$'\033[31m'; C_B=$'\033[1m'; C_0=$'\033[0m'
else
    C_DIM=; C_OK=; C_ERR=; C_B=; C_0=
fi

say()  { printf '%s\n' "$*"; }
step() { printf '%s→%s %s\n' "$C_B" "$C_0" "$*"; }
ok()   { printf '%s✓%s %s\n' "$C_OK" "$C_0" "$*"; }
note() { printf '%s  %s%s\n' "$C_DIM" "$*" "$C_0"; }
die()  { printf '%s✗%s %s\n' "$C_ERR" "$C_0" "$*" >&2; exit 1; }

# ---------------------------------------------------------------------------
# Preflight
# ---------------------------------------------------------------------------

need() {
    command -v "$1" >/dev/null 2>&1 || die "$1 is not installed. $2"
}

preflight() {
    need stellar "Install the Stellar CLI: https://developers.stellar.org/docs/tools/cli"
    need jq      "brew install jq"
    need curl    "curl ships with macOS and most Linux distributions"

    [ -n "${KEY:-}" ] || die "KEY is not set. Pass a Stellar CLI key name: make deploy KEY=deployer"
    stellar keys address "$KEY" >/dev/null 2>&1 \
        || die "Stellar CLI does not know a key called '$KEY'. Create one: stellar keys generate --fund $KEY --network $NETWORK"

    mkdir -p "$DEPLOY_DIR"
}

address_of() { stellar keys address "$1"; }

# ---------------------------------------------------------------------------
# Evidence
# ---------------------------------------------------------------------------

STEP_NO=0
EVIDENCE_ROWS=()

# record <milestone> <what> <hash-or-id> [verify-url]
#
# Appends a row to the in-memory table. write_evidence() renders it. Recording as we go rather than
# at the end means a script that dies half way still leaves the hashes it did collect.
record() {
    STEP_NO=$((STEP_NO + 1))
    local milestone="$1" what="$2" value="$3" url="${4:-}"
    if [ -n "$url" ]; then
        EVIDENCE_ROWS+=("| $milestone | $what | \`$value\` | [view]($url) |")
    else
        EVIDENCE_ROWS+=("| $milestone | $what | \`$value\` | — |")
    fi
    ok "$milestone · $what"
    note "$value"
}

expert_tx()       { echo "https://stellar.expert/explorer/testnet/tx/$1"; }
expert_contract() { echo "https://stellar.expert/explorer/testnet/contract/$1"; }
expert_account()  { echo "https://stellar.expert/explorer/testnet/account/$1"; }

write_evidence() {
    mkdir -p "$DEPLOY_DIR"
    {
        echo "# Evidence — SettleFlow SOW 1"
        echo
        echo "Generated by \`$(basename "${0}")\` on network \`$NETWORK\`."
        echo "Regenerate with \`make deploy\` and \`make demo\`; the milestones are defined in"
        echo "\`docs/14-evidence.md\`."
        echo
        echo "| # | Event | Hash / id | Verify |"
        echo "|---|---|---|---|"
        printf '%s\n' "${EVIDENCE_ROWS[@]}"
        echo
    } > "$EVIDENCE"
    ok "evidence written to $EVIDENCE"
}

# Persist addresses — never secrets — so every later script and the backend can find them.
write_env() {
    {
        echo "# Written by $(basename "${0}"). Addresses only; no secrets live here."
        echo "NETWORK=$NETWORK"
        echo "RPC_URL=$RPC_URL"
        echo "HORIZON_URL=$HORIZON_URL"
        for kv in "$@"; do echo "$kv"; done
    } > "$ENV_FILE"
    ok "addresses written to $ENV_FILE"
}
